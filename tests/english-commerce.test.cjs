const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.join(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const context={window:{}};
vm.createContext(context);
for(const family of ['crochet','hat','sticker','keychain','shirt','bird-toy','pouch']) vm.runInContext(read(family+'-data.js'),context);
vm.runInContext(read('language-commerce.js'),context);
const source=read('language.js');
vm.runInContext(source.slice(source.indexOf('  const copy ='),source.indexOf('  let language')).replace('const copy =','window.base ='),context);
const dictionary={...context.window.base,...context.window.BirbestEnglishCopy};
const missing=[];
const verify=text=>{if(/[\u0e00-\u0e7f]/.test(text)&&!dictionary[text]&&!/^\d+ ซอง(?: · \d+ กรัม)?$/.test(text))missing.push(text);};
const about=read('flow.js').split("else if(route==='about')")[1].split("else if(route==='privacy')")[0];
for(const match of about.matchAll(/>([^<>]+)</g)) if(!match[1].includes('${'))verify(match[1].trim());
for(const match of read('home-products.js').matchAll(/>([^<>]+)</g)) if(!match[1].includes('${')&&!match[1].includes('`')&&!match[1].includes('\n'))verify(match[1].trim());
for(const p of context.window.BirbestBirdToyProducts) for(const key of ['description','variants','notes','subtitle'])verify(p[key]);
for(const p of context.window.BirbestCrochetProducts)verify(`พวงกุญแจโครเชต์ ${p.title} จากคอลเลกชัน Birbest Little Goods`);
for(const p of context.window.BirbestPouchProducts)verify(`กระเป๋าโครเชต์ลาย${p.keywords} สำหรับเก็บของชิ้นเล็ก พร้อมห่วงคล้อง เพิ่มสีสันให้กระเป๋าใบโปรด`);
for(const p of context.window.BirbestStickerProducts)verify(`สติกเกอร์ลาย${p.keywords} จากคอลเลกชัน Chirp Mochi Crayon มาเป็นแพ็กคู่ตัวใหญ่และตัวเล็ก เติมสีสันให้สมุดและของใช้ชิ้นโปรด`);
for(const p of context.window.BirbestKeychainProducts)verify(`สินค้ารายการนี้คือลาย ${p.code} ภาพรวมคอลเลกชันใช้สำหรับเทียบลาย ไม่ใช่ชุดรวม 8 ชิ้น`);
assert.deepEqual([...new Set(missing)],[],'Untranslated About/body commerce copy');
for(const [th,en] of Object.entries(dictionary))assert.ok(!/[\u0e00-\u0e7f]/.test(en),`Thai remains in translation: ${th}`);
console.log('English About paragraphs, static commerce labels, all crochet/pouch/sticker descriptions, accessory warnings and keychain exclusions passed.');
