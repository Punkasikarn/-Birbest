from pathlib import Path
from PIL import Image
import hashlib
import json
import shutil

root = Path(__file__).resolve().parent.parent
source = Path('E:/06-BIRBEST/02_Product/07_Shirt')
files = sorted(source.glob('*.jfif'))
dest = root / 'assets/shirts'
dest.mkdir(parents=True, exist_ok=True)
# Main artwork, worn view, print detail, neck label, supplied size chart.
shots = []
for i, caption in [(3, 'ภาพรวมเสื้อครอปซันคอนัวร์'), (1, 'ภาพเสื้อขณะสวมใส่'), (2, 'รายละเอียดลายพิมพ์'), (0, 'ป้ายคอเสื้อ Birbest'), (4, 'ตารางไซซ์ S M L หน่วยนิ้ว')]:
    original = files[i]
    name = f'sun-conure-crop-{len(shots)+1}.jfif'
    shutil.copy2(original, dest / name)
    with Image.open(original) as im:
        shots.append(dict(file='shirts/'+name, caption=caption, width=im.width, height=im.height, source=original.name, sha256=hashlib.sha256(original.read_bytes()).hexdigest()))
products = [dict(slug='sun-conure-crop-shirt', title='Sun Conure Crop T-Shirt', kind='shirt', group='เสื้อ', price=390, shots=shots)]
(root / 'shirt-data.js').write_text('// Generated by tools/import-shirts.py; founder confirmed 390 THB, 2026-10-27.\nwindow.BirbestShirtProducts = '+json.dumps(products, ensure_ascii=False, indent=2)+';\n', encoding='utf-8')
print('1 shirt, 5 unchanged images.')
