from pathlib import Path
import hashlib
import json
import shutil

root = Path(__file__).resolve().parent.parent
source = Path('E:/06-BIRBEST/02_Product/09_Pouch')
inventory = json.loads((root / 'qa-pouches/inventory.json').read_text(encoding='utf-8'))
dest = root / 'assets/pouches'
dest.mkdir(parents=True, exist_ok=True)
shots = {}
for item in inventory:
    original = source / item['source']
    name = f'pouch-{item["index"]}.jfif'
    shutil.copy2(original, dest / name)
    shots[item['index']] = dict(file='pouches/'+name, width=item['width'], height=item['height'], source=item['source'], sha256=hashlib.sha256(original.read_bytes()).hexdigest())
rows = [
    ('african-grey', 'African Grey', 'แอฟริกันเกรย์', 1),
    ('amazon', 'Amazon', 'อเมซอน', 9),
    ('budgie-blue', 'Budgie Blue', 'หงส์หยก สีฟ้า', 12),
    ('budgie-purple', 'Budgie Purple', 'หงส์หยก สีม่วง', 18),
    ('cockatiel', 'Cockatiel', 'ค็อกคาเทล', 20),
    ('cockatoo', 'Cockatoo', 'กระตั้ว', 29),
    ('forpus', 'Forpus', 'ฟอพัส', 33),
    ('galah-cockatoo', 'Galah Cockatoo', 'กาล่า กระตั้ว', 38),
    ('golden-conure', 'Golden Conure', 'โกลเด้นคอนัวร์', 41),
    ('greencheek', 'Green-cheek', 'กรีนชีค', 45),
    ('major-mitchell-cockatoo', "Major Mitchell's Cockatoo", 'เมเจอร์มิตเชลล์ กระตั้ว', 54),
    ('blue-gold-macaw', 'Blue Gold Macaw', 'มาคอว์ บลูโกลด์', 59),
    ('scarlet-macaw', 'Scarlet Macaw', 'มาคอว์ สการ์เล็ต', 60),
    ('monk', 'Monk', 'ม็องค์', 66),
    ('sun-conure', 'Sun Conure', 'ซันคอนัวร์', 70),
]
products = []
for slug, title, keywords, cover in rows:
    folder = Path(inventory[cover]['source']).parent
    indices = [cover] + [i['index'] for i in inventory if Path(i['source']).parent == folder and i['index'] != cover] + [76, 75]
    products.append(dict(slug=slug+'-pouch', title=title+' Pouch', keywords=keywords, kind='pouch', group='กระเป๋าโครเชต์', price=149, shots=[shots[i] for i in indices]))
(root / 'pouch-data.js').write_text('// Generated by tools/import-pouches.py; founder confirmed 149 THB, 2026-10-27.\nwindow.BirbestPouchProducts = '+json.dumps(products, ensure_ascii=False, indent=2)+';\n', encoding='utf-8')
print(f'{len(products)} pouches, {len(shots)} unchanged images.')
