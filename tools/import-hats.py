from pathlib import Path
import hashlib
import json
import shutil

root = Path(__file__).resolve().parent.parent
source = Path('E:/06-BIRBEST/02_Product/03_Hat')
inventory = json.loads((root / 'qa-hats/inventory.json').read_text(encoding='utf-8'))
dest = root / 'assets/hats'
dest.mkdir(parents=True, exist_ok=True)
# Visual curation: omit duplicate compositions and unrelated photocard promotion.
rows = [('cockatiel-hat', 'Cockatiel Hat', [5, 9, 10, 16]),
        ('sun-conure-hat', 'Sun Conure Hat', [8, 0, 3, 1, 6, 4, 2, 7])]
products = []
for slug, title, indices in rows:
    shots = []
    for i in indices:
        item = inventory[i]
        original = source / item['source']
        name = f'{slug}-{len(shots)+1}{original.suffix.lower()}'
        shutil.copy2(original, dest / name)
        shots.append(dict(file='hats/'+name, width=item['width'], height=item['height'], source=item['source'], sha256=hashlib.sha256(original.read_bytes()).hexdigest()))
    products.append(dict(slug=slug, title=title, group='หมวก', kind='hat', price=559, shots=shots))
(root / 'hat-data.js').write_text('// Generated by tools/import-hats.py; 559 THB confirmed by founder.\nwindow.BirbestHatProducts = '+json.dumps(products, ensure_ascii=False, indent=2)+';\n', encoding='utf-8')
print(f'{len(products)} hats imported; originals unchanged.')
