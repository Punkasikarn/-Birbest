from pathlib import Path
import hashlib
import json
import shutil

root = Path(__file__).resolve().parent.parent
source = Path('E:/06-BIRBEST/02_Product/06_Keychain')
inventory = json.loads((root / 'qa-keychains/inventory.json').read_text(encoding='utf-8'))
dest = root / 'assets/keychains'
dest.mkdir(parents=True, exist_ok=True)
shots = {}
for item in inventory:
    original = source / item['source']
    name = f'keychain-{item["index"]}.jfif'
    shutil.copy2(original, dest / name)
    shots[item['index']] = dict(file='keychains/'+name, width=item['width'], height=item['height'], source=item['source'], sha256=hashlib.sha256(original.read_bytes()).hexdigest())
# AS codes read directly from each supplied product photograph.
products = [dict(slug=f'sun-conure-keychain-as{code:02}', title=f'Sun Conure Keychain AS{code:02}', code=f'AS{code:02}', group='พวงกุญแจภาพนก', kind='keychain', price=249, shots=[shots[index], shots[6]]) for code, index in enumerate([8, 2, 7, 3, 1, 0, 5, 4], 1)]
(root / 'keychain-data.js').write_text('// Generated by tools/import-keychains.py; founder confirmed 249 THB each, 2026-10-27.\nwindow.BirbestKeychainProducts = '+json.dumps(products, ensure_ascii=False, indent=2)+';\n', encoding='utf-8')
print('8 keychains, 9 unchanged image copies.')
