from pathlib import Path
import hashlib
import json
import shutil

root = Path(__file__).resolve().parent.parent
source = Path('E:/06-BIRBEST/02_Product/05_Stickers')
inventory = json.loads((root / 'qa-stickers/inventory.json').read_text(encoding='utf-8'))
dest = root / 'assets/stickers'
dest.mkdir(parents=True, exist_ok=True)
shots = {}
for i in [0, 1, 2, 3, 4, 5, 6, 7, 8, 12]:
    item = inventory[i]
    original = source / item['source']
    name = f'sticker-{i}{original.suffix.lower()}'
    shutil.copy2(original, dest / name)
    shots[i] = dict(file='stickers/'+name, width=item['width'], height=item['height'], source=item['source'], sha256=hashlib.sha256(original.read_bytes()).hexdigest())
rows = [('green-cheek-stickers', 'Green-cheek Stickers', 'กรีนชีค', 0),
        ('pineapple-stickers', 'Pineapple Stickers', 'กรีนชีค พายแอปเปิล', 1),
        ('cockatiel-stickers', 'Cockatiel Stickers', 'ค็อกคาเทล', 2),
        ('budgie-stickers', 'Budgie Stickers', 'หงส์หยก', 3),
        ('lovebird-stickers', 'Lovebird Stickers', 'เลิฟเบิร์ด', 4),
        ('sun-conure-stickers', 'Sun Conure Stickers', 'ซันคอนัวร์', 5)]
products = []
for slug, title, keywords, i in rows:
    indices = [i, 12] + ([7] if i == 2 else [8] if i == 5 else []) + [6]
    products.append(dict(slug=slug, title=title, keywords=keywords, group='สติกเกอร์', kind='sticker', price=29, shots=[shots[j] for j in indices]))
(root / 'sticker-data.js').write_text('// Generated by tools/import-stickers.py; founder confirmed 29 THB per pair, 2026-10-27.\nwindow.BirbestStickerProducts = '+json.dumps(products, ensure_ascii=False, indent=2)+';\n', encoding='utf-8')
print('6 sticker designs, 10 unchanged image copies.')
